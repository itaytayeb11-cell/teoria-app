export function assignSubCategory(category, text, answers) {
  const haystack = `${text} ${answers.join(' ')}`;
  const rules = RULES[category] ?? [];
  for (const rule of rules) {
    if (rule.any.some((kw) => haystack.includes(kw))) {
      return rule.name;
    }
  }
  return DEFAULT_SUB[category] ?? 'כללי';
}

